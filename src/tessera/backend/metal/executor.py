"""Running a whole model on the GPU: one library, one command buffer per run.

``MetalModel`` compiles every kernel of an ``ExecutionPlan`` into one MSL
library and allocates one shared-storage buffer each for the arena, the
constant blob, every model input and every model output. Each launch binds
its parameters to (buffer, byte offset) pairs taken from the plan's
``BufferRef``s. A run encodes all launches into one concurrent compute
encoder; a launch gets a memory barrier only if it reads bytes an earlier
launch writes, or writes bytes an earlier launch reads or writes, since the
last barrier. Independent kernels (the two branches of a residual block) may
therefore overlap on the GPU.
"""

from __future__ import annotations

import statistics
from collections.abc import Mapping, Sequence
from dataclasses import dataclass

import numpy as np

from tessera.backend.base import KernelTime
from tessera.backend.metal import runtime
from tessera.backend.metal.codegen import Kernel, generate, module_source
from tessera.ir.graph import NDArray, TensorType
from tessera.plan import BufferRef, ExecutionPlan, StorageKind
from tessera.target import Target
from tessera.tir.stmt import PrimFunc


@dataclass(frozen=True)
class _Span:
    """Bytes ``[start, stop)`` of one buffer."""

    buffer: int  # id of the runtime.Buffer
    start: int
    stop: int

    def overlaps(self, other: _Span) -> bool:
        return self.buffer == other.buffer and self.start < other.stop and other.start < self.stop


@dataclass(frozen=True)
class LaunchInfo:
    """How one launch of the plan was encoded."""

    kernel: str
    grid: tuple[int, int, int]
    threads: tuple[int, int, int]
    barrier: bool  # waits for earlier launches


def plan_barriers(accesses: Sequence[tuple[Sequence[_Span], Sequence[_Span]]]) -> list[bool]:
    """For launches given as (reads, writes), whether each needs a barrier before it:
    it reads bytes written, or writes bytes read or written, by a launch since the
    last barrier."""
    barriers: list[bool] = []
    pending_reads: list[_Span] = []
    pending_writes: list[_Span] = []
    for reads, writes in accesses:
        barrier = any(r.overlaps(w) for r in reads for w in pending_writes) or any(
            w.overlaps(o) for w in writes for o in (*pending_reads, *pending_writes)
        )
        if barrier:
            pending_reads, pending_writes = [], []
        pending_reads.extend(reads)
        pending_writes.extend(writes)
        barriers.append(barrier)
    return barriers


class MetalModel:
    """A model compiled for the GPU (implements ``tessera.backend.base.CompiledModel``)."""

    def __init__(
        self, plan: ExecutionPlan, target: Target, device: runtime.Device | None = None
    ) -> None:
        self._target = target
        self._plan = plan
        self.device = device or runtime.device()
        limit = self.device.info.max_threadgroup_memory
        order = _kernel_order(plan)
        self.kernels: dict[str, Kernel] = {
            name: generate(plan.funcs[name], max_threadgroup_memory=limit) for name in order
        }
        self.source = module_source(
            list(self.kernels.values()), header=f"{plan.name}: generated by Tessera"
        )
        library = self.device.compile(self.source)
        self.pipelines = {name: library.pipeline(k.name) for name, k in self.kernels.items()}

        memory = plan.memory
        self.arena = self.device.buffer(memory.arena_bytes)
        self.constants = self.device.buffer(len(memory.constants))
        if len(memory.constants):
            self.constants.view(np.uint8, (len(memory.constants),))[:] = memory.constants
        self.input_buffers = [self.device.buffer(t.nbytes) for _, t in plan.inputs]
        self.output_buffers = [self.device.buffer(t.nbytes) for _, t in plan.outputs]
        self.scratch = {
            name: [self.device.buffer(b.nbytes) for b in k.scratch]
            for name, k in self.kernels.items()
        }
        self.program, self.launches = self._encode()

    # -- CompiledModel

    @property
    def target(self) -> Target:
        return self._target

    @property
    def inputs(self) -> list[tuple[str, TensorType]]:
        return list(self._plan.inputs)

    @property
    def outputs(self) -> list[tuple[str, TensorType]]:
        return list(self._plan.outputs)

    def run(self, inputs: Mapping[str, NDArray]) -> dict[str, NDArray]:
        """Run once; returns new arrays."""
        self.set_inputs(inputs)
        self.program.run(1)
        return {name: view.copy() for name, view in self.output_views().items()}

    def benchmark(
        self, inputs: Mapping[str, NDArray], *, warmup: int = 3, repeat: int = 20
    ) -> list[float]:
        """Wall-clock seconds of each timed run, from encoding to completion.
        Warms up with ``warmup`` runs, and more if those take under 50 ms of GPU
        time, so that the GPU clock has ramped up."""
        self.set_inputs(inputs)
        self.warm_up(warmup)
        return self.program.run(repeat).wall

    def gpu_benchmark(
        self, inputs: Mapping[str, NDArray], *, warmup: int = 3, repeat: int = 20
    ) -> list[float]:
        """Seconds the GPU spends on each timed run's command buffer."""
        self.set_inputs(inputs)
        self.warm_up(warmup)
        return self.program.run(repeat).gpu

    def warm_up(self, runs: int, seconds: float = 0.05) -> None:
        """Run at least ``runs`` times and for at least ``seconds`` of GPU time."""
        elapsed, done = 0.0, 0
        while done < runs or elapsed < seconds:
            elapsed += sum(self.program.run(1).gpu)
            done += 1

    def profile(self, inputs: Mapping[str, NDArray], *, repeat: int = 10) -> list[KernelTime]:
        """Median GPU time of each launch over ``repeat`` profiled runs, in launch order."""
        self.set_inputs(inputs)
        self.program.run(1)
        samples = [self.program.profile() for _ in range(max(repeat, 1))]
        return [
            KernelTime(launch.kernel, statistics.median(s[i] for s in samples))
            for i, launch in enumerate(self.launches)
        ]

    def sources(self) -> dict[str, str]:
        return {"kernels.metal": self.source}

    # -- buffers

    def input_views(self) -> dict[str, NDArray]:
        """NumPy arrays over the input buffers: writing them sets the next run's inputs."""
        return {
            name: buf.view(t.dtype, t.shape)
            for (name, t), buf in zip(self._plan.inputs, self.input_buffers, strict=True)
        }

    def output_views(self) -> dict[str, NDArray]:
        """NumPy arrays over the output buffers (overwritten by every run)."""
        return {
            name: buf.view(t.dtype, t.shape)
            for (name, t), buf in zip(self._plan.outputs, self.output_buffers, strict=True)
        }

    def set_inputs(self, inputs: Mapping[str, NDArray]) -> None:
        views = self.input_views()
        missing = set(views) - set(inputs)
        if missing:
            raise ValueError(f"missing inputs: {sorted(missing)}")
        for name, view in views.items():
            value = np.asarray(inputs[name])
            if value.shape != view.shape:
                raise ValueError(f"input {name} has shape {value.shape}, expected {view.shape}")
            view[...] = value

    def _buffer(self, ref: BufferRef) -> runtime.Buffer:
        if ref.kind is StorageKind.ARENA:
            return self.arena
        if ref.kind is StorageKind.CONSTANT:
            return self.constants
        if ref.kind is StorageKind.INPUT:
            return self.input_buffers[ref.index]
        return self.output_buffers[ref.index]

    def _encode(self) -> tuple[runtime.Program, list[LaunchInfo]]:
        bound: list[list[tuple[runtime.Buffer, int]]] = []
        accesses: list[tuple[list[_Span], list[_Span]]] = []
        for launch in self._plan.launches:
            kernel = self.kernels[launch.kernel]
            if len(launch.args) != len(kernel.params):
                raise ValueError(
                    f"launch of {launch.kernel} passes {len(launch.args)} buffers, "
                    f"the kernel takes {len(kernel.params)}"
                )
            args: list[tuple[runtime.Buffer, int]] = []
            reads: list[_Span] = []
            writes: list[_Span] = []
            for ref, param in zip(launch.args, kernel.params, strict=True):
                if ref.nbytes < param.nbytes:
                    raise ValueError(
                        f"{launch.kernel}: {param.name} needs {param.nbytes} bytes, "
                        f"the plan gives {ref.nbytes}"
                    )
                buffer = self._buffer(ref)
                if ref.offset + param.nbytes > buffer.nbytes:
                    raise ValueError(f"{launch.kernel}: {param.name} runs past its buffer")
                args.append((buffer, ref.offset))
                span = _Span(id(buffer), ref.offset, ref.offset + param.nbytes)
                (writes if param.written else reads).append(span)
            for buffer in self.scratch[launch.kernel]:
                args.append((buffer, 0))
                writes.append(_Span(id(buffer), 0, buffer.nbytes))
            bound.append(args)
            accesses.append((reads, writes))

        program = self.device.program()
        launches: list[LaunchInfo] = []
        for launch, args, barrier in zip(
            self._plan.launches, bound, plan_barriers(accesses), strict=True
        ):
            kernel = self.kernels[launch.kernel]
            program.add(
                self.pipelines[launch.kernel],
                kernel.grid,
                kernel.threads,
                args,
                barrier=barrier,
                label=launch.kernel,
            )
            launches.append(LaunchInfo(launch.kernel, kernel.grid, kernel.threads, barrier))
        return program, launches


def _kernel_order(plan: ExecutionPlan) -> list[str]:
    """Kernels in order of first launch, then any the plan does not launch."""
    order: list[str] = []
    for launch in plan.launches:
        if launch.kernel not in order:
            if launch.kernel not in plan.funcs:
                raise ValueError(f"the plan launches {launch.kernel}, which it does not define")
            order.append(launch.kernel)
    order.extend(sorted(set(plan.funcs) - set(order)))
    return order


def run_func(func: PrimFunc, args: Sequence[NDArray], *, timeout: float = 10.0) -> None:
    """Run ``func`` once on the GPU with ``args`` (one array per parameter) and
    write what it stores back into those arrays, like ``tir.interpret``."""
    device = runtime.device()
    kernel = generate(func, max_threadgroup_memory=device.info.max_threadgroup_memory)
    if len(args) != len(kernel.params):
        raise ValueError(f"{func.name} takes {len(kernel.params)} arrays, got {len(args)}")
    pipeline = device.compile(module_source([kernel])).pipeline(kernel.name)
    buffers: list[runtime.Buffer] = []
    for param, array in zip(kernel.params, args, strict=True):
        if tuple(array.shape) != param.shape:
            raise ValueError(f"{param.name} has shape {param.shape}, got {array.shape}")
        buffer = device.buffer(param.nbytes)
        buffer.view(param.dtype, param.shape)[...] = array
        buffers.append(buffer)
    buffers.extend(device.buffer(b.nbytes) for b in kernel.scratch)
    program = device.program()
    program.add(pipeline, kernel.grid, kernel.threads, [(b, 0) for b in buffers])
    program.run(1, timeout=timeout)
    for param, array, buffer in zip(kernel.params, args, buffers, strict=False):
        if param.written:
            array[...] = buffer.view(param.dtype, param.shape)
