"""One C translation unit per model, loaded with ctypes.

``model_sources`` writes ``model.c``: every kernel of the plan, then
``tessera_run``, which calls the kernels in launch order with pointers into
the inputs, the outputs, the arena and the constant blob. A run of the model
is that one native call. ``tessera_profile`` does the same and records the
time of each launch; ``tessera_benchmark`` times whole runs without leaving C.

``CModel`` owns the arena and a 128-byte-aligned copy of the constant blob.
It is not reentrant: runs of one model are serialized by a lock.
"""

from __future__ import annotations

import ctypes
import statistics
import threading
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from tessera.backend.base import KernelTime
from tessera.backend.c import build as cbuild
from tessera.backend.c.codegen import KernelCode, c_type, generate_kernel
from tessera.backend.c.microkernels import header_files
from tessera.ir.graph import NDArray, TensorType
from tessera.plan import BufferRef, ExecutionPlan, StorageKind
from tessera.target import Target
from tessera.tir.stmt import PrimFunc

ABI_VERSION = 1
_ALIGN = 128

_RUN_PARAMS = "void* const* inputs, void* const* outputs, uint8_t* arena, uint8_t* constants"
_RUN_ARGS = "inputs, outputs, arena, constants"


@dataclass(frozen=True)
class ModelSource:
    """The files of one model's build; ``files["model.c"]`` is compiled."""

    files: dict[str, str]
    kernels: dict[str, KernelCode]


def model_sources(plan: ExecutionPlan, target: Target) -> ModelSource:
    """Generate the C files of ``plan`` for ``target``."""
    order: list[str] = []
    for launch in plan.launches:
        if launch.kernel not in plan.funcs:
            raise ValueError(f"launch of {launch.kernel!r}, which has no PrimFunc in the plan")
        if launch.kernel not in order:
            order.append(launch.kernel)
    kernels = {name: generate_kernel(plan.funcs[name], target.isa) for name in order}
    symbols = [k.name for k in kernels.values()]
    if len(set(symbols)) != len(symbols):
        raise ValueError(f"kernel names collide in C: {symbols}")

    headers: list[str] = []
    for code in kernels.values():
        headers += [h for h in code.headers if h not in headers]

    out = [
        f"/* {plan.name}: generated by Tessera for c:{target.isa}, {target.threads} threads. */",
        "",
        *cbuild.runtime_defines(target),
        '#include "tessera_runtime.h"',
        *(f'#include "{h}"' for h in headers),
        "",
    ]
    for code in kernels.values():
        out += [code.text]

    calls = []
    for i, launch in enumerate(plan.launches):
        code = kernels[launch.kernel]
        if len(launch.args) != len(code.params):
            raise ValueError(
                f"launch {i} of {launch.kernel} passes {len(launch.args)} buffers to "
                f"{len(code.params)} parameters"
            )
        args = []
        for ref, param in zip(launch.args, code.params, strict=True):
            need = param.numel * param.dtype.itemsize
            if ref.nbytes < need:
                raise ValueError(
                    f"launch {i} of {launch.kernel}: {param.name} needs {need} bytes, "
                    f"its buffer has {ref.nbytes}"
                )
            args.append(_pointer(ref, c_type(param.dtype)))
        calls.append(f"{code.name}({', '.join(args)});")

    out.append(f"TSR_EXPORT int32_t tessera_abi(void) {{ return {ABI_VERSION}; }}")
    out.append("")
    out += _forget_constants(headers)
    out.append(f"TSR_EXPORT void tessera_run({_RUN_PARAMS}) {{")
    out.append("  tsr_prefer_performance_cores();")
    out += [f"  {c}" for c in calls]
    out.append("}")
    out.append("")
    out.append(f"TSR_EXPORT void tessera_profile({_RUN_PARAMS}, double* seconds) {{")
    out.append("  tsr_prefer_performance_cores();")
    out.append("  double start;")
    for i, c in enumerate(calls):
        out += ["  start = tsr_now();", f"  {c}", f"  seconds[{i}] = tsr_now() - start;"]
    out.append("}")
    out.append("")
    out += [
        f"TSR_EXPORT void tessera_benchmark({_RUN_PARAMS}, int32_t warmup, int32_t repeat,",
        "                                  double* seconds) {",
        f"  for (int32_t i = 0; i < warmup; ++i) tessera_run({_RUN_ARGS});",
        "  for (int32_t i = 0; i < repeat; ++i) {",
        "    double start = tsr_now();",
        f"    tessera_run({_RUN_ARGS});",
        "    seconds[i] = tsr_now() - start;",
        "  }",
        "}",
        "",
    ]
    files = {"model.c": "\n".join(out), **header_files(["tessera_runtime.h", *headers])}
    return ModelSource(files, kernels)


def _forget_constants(headers: list[str]) -> list[str]:
    """``tessera_forget_constants``: drops the microkernels' packings of
    constant operands, so that none is reused for other data later placed at
    the same address."""
    packs = any(h != "tessera_runtime.h" for h in headers)
    body = "  tsr_forget_panels();" if packs else ""
    return ["TSR_EXPORT void tessera_forget_constants(void) {", *([body] if body else []), "}", ""]


def _pointer(ref: BufferRef, ctype: str) -> str:
    if ref.kind is StorageKind.INPUT:
        base = f"(uint8_t*)inputs[{ref.index}]"
    elif ref.kind is StorageKind.OUTPUT:
        base = f"(uint8_t*)outputs[{ref.index}]"
    elif ref.kind is StorageKind.ARENA:
        base = "arena"
    else:
        base = "constants"
    if ref.offset:
        return f"({ctype}*)({base} + {ref.offset})"
    if ref.kind in (StorageKind.ARENA, StorageKind.CONSTANT):
        return f"({ctype}*){base}"
    return f"({ctype}*){base[len('(uint8_t*)') :]}"


def aligned_empty(nbytes: int, align: int = _ALIGN) -> NDArray:
    """A zeroed uint8 array of ``nbytes`` whose data starts on an ``align`` boundary."""
    raw = np.zeros(nbytes + align, np.uint8)
    start = -raw.ctypes.data % align
    return raw[start : start + nbytes]


class CModel:
    """A model compiled to a shared library (``tessera.backend.base.CompiledModel``)."""

    def __init__(self, plan: ExecutionPlan, target: Target, source: ModelSource, library: Path):
        self._target = target
        self._plan = plan
        self._source = source
        self._library = library
        self._lib = ctypes.CDLL(str(library))
        if self._lib.tessera_abi() != ABI_VERSION:
            raise RuntimeError(f"{library} was built for another runtime version")
        # The library may be shared with a model loaded earlier whose constants
        # lived at addresses this one's may reuse.
        self._lib.tessera_forget_constants()
        ptrs = [ctypes.c_void_p] * 4
        self._run = self._lib.tessera_run
        self._run.argtypes = ptrs
        self._run.restype = None
        self._profile = self._lib.tessera_profile
        self._profile.argtypes = [*ptrs, ctypes.c_void_p]
        self._profile.restype = None
        self._bench = self._lib.tessera_benchmark
        self._bench.argtypes = [*ptrs, ctypes.c_int32, ctypes.c_int32, ctypes.c_void_p]
        self._bench.restype = None
        self._arena = aligned_empty(max(plan.memory.arena_bytes, 1))
        blob = np.ascontiguousarray(plan.memory.constants, dtype=np.uint8).reshape(-1)
        self._constants = aligned_empty(max(blob.size, 1))
        self._constants[: blob.size] = blob
        self._lock = threading.Lock()

    @property
    def target(self) -> Target:
        return self._target

    @property
    def inputs(self) -> list[tuple[str, TensorType]]:
        return list(self._plan.inputs)

    @property
    def outputs(self) -> list[tuple[str, TensorType]]:
        return list(self._plan.outputs)

    @property
    def plan(self) -> ExecutionPlan:
        """The plan this model runs."""
        return self._plan

    @property
    def library(self) -> Path:
        """The shared library this model runs."""
        return self._library

    def sources(self) -> dict[str, str]:
        """``model.c`` and the headers it includes."""
        return dict(self._source.files)

    def run(self, inputs: Mapping[str, NDArray]) -> dict[str, NDArray]:
        """Run once and return new output arrays."""
        args = self._inputs(inputs)
        outs = [np.empty(t.shape, t.dtype.numpy) for _, t in self._plan.outputs]
        with self._lock:
            self._call(self._run, args, outs)
            result = {}
            for (name, t), out in zip(self._plan.outputs, outs, strict=True):
                ref = self._plan.memory.refs[name]
                if ref.kind is not StorageKind.OUTPUT:
                    out[...] = self._read(ref, t, args)
                result[name] = out
        return result

    def benchmark(
        self, inputs: Mapping[str, NDArray], *, warmup: int = 3, repeat: int = 20
    ) -> list[float]:
        """Seconds of each of ``repeat`` runs after ``warmup`` untimed ones."""
        args = self._inputs(inputs)
        outs = [np.empty(t.shape, t.dtype.numpy) for _, t in self._plan.outputs]
        seconds = np.zeros(max(repeat, 1), np.float64)
        with self._lock:
            self._call(self._bench, args, outs, warmup, repeat, seconds.ctypes.data)
        return [float(s) for s in seconds[:repeat]]

    def profile(self, inputs: Mapping[str, NDArray], *, repeat: int = 10) -> list[KernelTime]:
        """Median time of every launch over ``repeat`` profiled runs (one warmup run first)."""
        args = self._inputs(inputs)
        outs = [np.empty(t.shape, t.dtype.numpy) for _, t in self._plan.outputs]
        n = len(self._plan.launches)
        samples = np.zeros((max(repeat, 1), max(n, 1)), np.float64)
        with self._lock:
            self._call(self._run, args, outs)
            for r in range(repeat):
                self._call(self._profile, args, outs, samples[r].ctypes.data)
        return [
            KernelTime(launch.kernel, float(statistics.median(samples[:repeat, i])))
            for i, launch in enumerate(self._plan.launches)
        ]

    def _inputs(self, inputs: Mapping[str, NDArray]) -> list[NDArray]:
        arrays = []
        for name, t in self._plan.inputs:
            if name not in inputs:
                raise KeyError(f"missing input {name!r}")
            array = np.ascontiguousarray(inputs[name], dtype=t.dtype.numpy)
            if array.shape != t.shape:
                raise ValueError(f"input {name!r} has shape {array.shape}, expected {t.shape}")
            arrays.append(array)
        return arrays

    def _call(
        self, fn: Callable[..., object], ins: list[NDArray], outs: list[NDArray], *extra: object
    ) -> None:
        in_ptrs = (ctypes.c_void_p * max(len(ins), 1))(*[a.ctypes.data for a in ins])
        out_ptrs = (ctypes.c_void_p * max(len(outs), 1))(*[a.ctypes.data for a in outs])
        fn(in_ptrs, out_ptrs, self._arena.ctypes.data, self._constants.ctypes.data, *extra)

    def _read(self, ref: BufferRef, t: TensorType, ins: list[NDArray]) -> NDArray:
        """An output that lives in other storage (an input, a constant, the arena)."""
        if ref.kind is StorageKind.INPUT:
            storage = ins[ref.index].reshape(-1).view(np.uint8)
        elif ref.kind is StorageKind.CONSTANT:
            storage = self._constants
        else:
            storage = self._arena
        raw = storage[ref.offset : ref.offset + t.nbytes]
        return raw.view(t.dtype.numpy).reshape(t.shape)


def build_model(plan: ExecutionPlan, target: Target) -> CModel:
    """Generate, compile (or reuse) and load the shared library of ``plan``."""
    source = model_sources(plan, target)
    library = cbuild.build(source.files, "model.c", target, kind="shared")
    return CModel(plan, target, source, library)


def kernel_sources(func: PrimFunc, target: Target) -> dict[str, str]:
    """``kernel.c``: one kernel and ``tessera_kernel(void** args)``, which calls it."""
    code = generate_kernel(func, target.isa)
    casts = ", ".join(f"({c_type(p.dtype)}*)args[{i}]" for i, p in enumerate(func.params))
    text = "\n".join(
        [
            f"/* {func.name}: generated by Tessera for c:{target.isa}, "
            f"{target.threads} threads. */",
            "",
            *cbuild.runtime_defines(target),
            '#include "tessera_runtime.h"',
            *(f'#include "{h}"' for h in code.headers),
            "",
            code.text,
            f"TSR_EXPORT int32_t tessera_abi(void) {{ return {ABI_VERSION}; }}",
            "",
            *_forget_constants(list(code.headers)),
            "TSR_EXPORT void tessera_kernel(void* const* args) {",
            "  tsr_prefer_performance_cores();",
            f"  {code.name}({casts});",
            "}",
            "",
        ]
    )
    return {"kernel.c": text, **header_files(["tessera_runtime.h", *code.headers])}


def run_kernel(func: PrimFunc, args: Sequence[NDArray], target: Target | None = None) -> None:
    """Compile ``func`` and call it once on ``args``, one C-contiguous array per
    parameter with the parameter's shape and dtype; outputs are written in
    place (the native counterpart of ``tir.interpret``)."""
    target = target or Target()
    if len(args) != len(func.params):
        raise ValueError(f"{func.name} takes {len(func.params)} arrays, got {len(args)}")
    for array, param in zip(args, func.params, strict=True):
        if array.shape != param.shape or array.dtype != param.dtype.numpy:
            raise ValueError(
                f"{param.name}: expected {param.dtype}{list(param.shape)}, "
                f"got {array.dtype}{list(array.shape)}"
            )
        if not array.flags.c_contiguous:
            raise ValueError(f"{param.name}: the array must be C-contiguous")
    library = cbuild.build(kernel_sources(func, target), "kernel.c", target, kind="shared")
    lib = ctypes.CDLL(str(library))
    fn = lib.tessera_kernel
    fn.argtypes = [ctypes.c_void_p]
    fn.restype = None
    pointers = (ctypes.c_void_p * max(len(args), 1))(*[a.ctypes.data for a in args])
    lib.tessera_forget_constants()  # earlier calls' arrays may have lived here
    fn(pointers)
