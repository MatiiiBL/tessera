"""Graph statistics of the benchmark models: node counts, kernels, memory and pass times.

    uv run python scripts/graph_stats.py [--models data/models] [--out results/graph]

For each exported model this reports the ONNX node count, the nodes after
import and after ``passes.optimize`` (with and without folding), the number
of kernels after fusion (and with fusion off, and with each fusion rule
off), the bytes kernels read and write, the arena size against the sum of
all intermediate tensors, and the median time of import, optimize, fuse and
plan_memory over three runs. It writes ``models.json`` and ``models.md``.
"""

from __future__ import annotations

import argparse
import json
import platform
import statistics
import sys
import time
from collections import Counter
from collections.abc import Callable, Sequence
from dataclasses import replace
from datetime import date
from pathlib import Path
from typing import Any

import onnx

from tessera.frontend import onnx as onnx_frontend
from tessera.ir import Graph
from tessera.passes import FusionOptions, fuse, optimize, plan_memory
from tessera.plan import FusedGroup, StorageKind

ROOT = Path(__file__).resolve().parent.parent
NAMES = ("resnet50", "mobilenet_v2", "bert", "gpt2")
RULES = ("epilogue", "prologue", "injective", "duplicate")
REPEAT = 3


def _median_time[T](fn: Callable[[], T]) -> tuple[T, float]:
    times, result = [], None
    for _ in range(REPEAT):
        start = time.perf_counter()
        result = fn()
        times.append(time.perf_counter() - start)
    assert result is not None
    return result, statistics.median(times)


def _kernels(groups: Sequence[FusedGroup]) -> list[FusedGroup]:
    return [g for g in groups if not g.is_view]


def _traffic(groups: Sequence[FusedGroup]) -> dict[str, int]:
    """Bytes every kernel reads (inputs, weights included) and writes (its output)."""
    kernels = _kernels(groups)
    return {
        "read_bytes": sum(v.type.nbytes for g in kernels for v in g.inputs),
        "write_bytes": sum(g.output.type.nbytes for g in kernels),
    }


def _memory(graph: Graph, groups: Sequence[FusedGroup]) -> dict[str, int]:
    plan = plan_memory(graph, groups)
    arena = {(r.offset, r.nbytes): r for r in plan.refs.values() if r.kind is StorageKind.ARENA}
    # Views share their input's bytes, so each storage is counted once.
    return {
        "arena_bytes": plan.arena_bytes,
        "intermediate_bytes": sum(
            g.output.type.nbytes
            for g in _kernels(groups)
            if plan.refs[g.output.name].kind is StorageKind.ARENA
        ),
        "arena_buffers": len(arena),
        "constant_bytes": int(plan.constants.size),
    }


def model_stats(path: Path) -> dict[str, Any]:
    proto = onnx.load(str(path))
    onnx_ops = Counter(n.op_type for n in proto.graph.node)
    imported, t_import = _median_time(lambda: onnx_frontend.load(proto))
    optimized, t_optimize = _median_time(lambda: optimize(imported))
    groups, t_fuse = _median_time(lambda: fuse(optimized))
    _, t_plan = _median_time(lambda: plan_memory(optimized, groups))
    unfolded = optimize(imported, fold=False)
    unfused = fuse(optimized, enabled=False)

    ablations = {}
    for rule in RULES:
        options = replace(FusionOptions(), **{rule: False})
        ablations[f"no_{rule}"] = len(_kernels(fuse(optimized, options=options)))

    return {
        "onnx_nodes": len(proto.graph.node),
        "onnx_ops": dict(onnx_ops.most_common()),
        "imported_nodes": len(imported.nodes),
        "optimized_nodes": len(optimized.nodes),
        "optimized_nodes_no_fold": len(unfolded.nodes),
        "optimized_ops": dict(Counter(n.op for n in optimized.nodes).most_common()),
        "kernels": len(_kernels(groups)),
        "views": len(groups) - len(_kernels(groups)),
        "kernels_no_fusion": len(_kernels(unfused)),
        "kernels_no_fold": len(_kernels(fuse(unfolded))),
        "kernels_rule_off": ablations,
        "patterns": dict(Counter(g.pattern for g in _kernels(groups)).most_common()),
        "fused": {**_memory(optimized, groups), **_traffic(groups)},
        "unfused": {**_memory(optimized, unfused), **_traffic(unfused)},
        "seconds": {
            "import": round(t_import, 5),
            "optimize": round(t_optimize, 5),
            "fuse": round(t_fuse, 5),
            "plan_memory": round(t_plan, 5),
        },
    }


def _mib(n: int) -> str:
    return f"{n / 2**20:.1f}"


def markdown(results: dict[str, Any]) -> str:
    models = results["models"]
    lines = [
        "# Graph statistics of the benchmark models",
        "",
        f"Generated by `uv run python scripts/graph_stats.py` on {results['date']} "
        f"({results['machine']}). {results['note']}",
        "",
        "## Nodes and kernels",
        "",
        "| Model | ONNX nodes | Imported | Optimized | Optimized, no folding "
        "| Kernels | Kernels, fusion off |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for name, m in models.items():
        lines.append(
            f"| {name} | {m['onnx_nodes']} | {m['imported_nodes']} | {m['optimized_nodes']} "
            f"| {m['optimized_nodes_no_fold']} | {m['kernels']} | {m['kernels_no_fusion']} |"
        )
    lines += [
        "",
        "Kernels exclude view groups (Reshape only), which run no code. Import counts the "
        "Tessera nodes left after import-time evaluation of constant subgraphs.",
        "",
        "## Kernels with one fusion rule turned off",
        "",
        "| Model | All rules | No epilogue | No prologue | No injective | No duplication "
        "| Fold off |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for name, m in models.items():
        off = m["kernels_rule_off"]
        lines.append(
            f"| {name} | {m['kernels']} | {off['no_epilogue']} | {off['no_prologue']} "
            f"| {off['no_injective']} | {off['no_duplicate']} | {m['kernels_no_fold']} |"
        )
    lines += [
        "",
        "## Memory (MiB)",
        "",
        "| Model | Arena | Intermediates | Arena, fusion off | Intermediates, fusion off "
        "| Kernel writes | Kernel writes, fusion off | Constants |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for name, m in models.items():
        f, u = m["fused"], m["unfused"]
        lines.append(
            f"| {name} | {_mib(f['arena_bytes'])} | {_mib(f['intermediate_bytes'])} "
            f"| {_mib(u['arena_bytes'])} | {_mib(u['intermediate_bytes'])} "
            f"| {_mib(f['write_bytes'])} | {_mib(u['write_bytes'])} "
            f"| {_mib(f['constant_bytes'])} |"
        )
    lines += [
        "",
        "Intermediates is the sum of every tensor a kernel writes to the arena; the arena "
        "holds them in less space by reusing bytes once a tensor's last reader has run. "
        "Kernel writes counts every kernel output, graph outputs included.",
        "",
        "## Pass times (milliseconds, median of 3)",
        "",
        "| Model | Import | Optimize | Fuse | Plan memory |",
        "|---|---:|---:|---:|---:|",
    ]
    for name, m in models.items():
        s = {k: v * 1000 for k, v in m["seconds"].items()}
        lines.append(
            f"| {name} | {s['import']:.1f} | {s['optimize']:.1f} | {s['fuse']:.1f} "
            f"| {s['plan_memory']:.1f} |"
        )
    lines += ["", "## Kernel patterns", "", "| Model | Patterns |", "|---|---|"]
    for name, m in models.items():
        patterns = ", ".join(f"{k} {v}" for k, v in m["patterns"].items())
        lines.append(f"| {name} | {patterns} |")
    return "\n".join(lines) + "\n"


# Light and dark values of each role; the categorical slots follow one fixed order.
_COLORS = {
    "surface": ("#fcfcfb", "#1a1a19"),
    "text": ("#0b0b0b", "#f0efec"),
    "muted": ("#52514e", "#c3c2b7"),
    "grid": ("#e4e3df", "#33332f"),
    "s1": ("#2a78d6", "#3987e5"),
    "s2": ("#eb6834", "#d95926"),
    "s3": ("#1baf7a", "#199e70"),
}


def memory_chart(results: dict[str, Any]) -> str:
    """A grouped bar chart (SVG, light and dark) of intermediates against arena size."""
    series: list[tuple[str, str, Callable[[dict[str, Any]], int]]] = [
        ("s1", "Intermediates, fusion off", lambda m: int(m["unfused"]["intermediate_bytes"])),
        ("s2", "Intermediates, fused", lambda m: int(m["fused"]["intermediate_bytes"])),
        ("s3", "Arena, fused", lambda m: int(m["fused"]["arena_bytes"])),
    ]
    models = results["models"]
    bar, gap, group_gap = 14, 2, 22
    left, right, top = 112, 64, 76
    width = 720
    plot = width - left - right
    peak: float = max(fn(m) for m in models.values() for _, _, fn in series) / 2**20
    step = 50 if peak > 100 else 10
    limit = step * -(-peak // step)
    group = len(series) * bar + (len(series) - 1) * gap
    height = top + len(models) * (group + group_gap) + 24

    def x(mib: float) -> float:
        return left + plot * mib / limit

    css = ["".join(f"--{k}:{v[i]};" for k, v in _COLORS.items()) for i in (0, 1)]
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" aria-labelledby="t d">',
        "<title id='t'>Intermediate tensors and arena size of the benchmark models</title>",
        "<desc id='d'>For each model, megabytes of intermediate tensors with fusion off and "
        "on, and the size of the arena that holds the fused model's intermediates.</desc>",
        "<style>",
        f"svg{{{css[0]}}}",
        f"@media (prefers-color-scheme: dark){{svg{{{css[1]}}}}}",
        "text{font-family:-apple-system,system-ui,'Segoe UI',sans-serif;font-size:12px}",
        ".title{font-size:14px;font-weight:600;fill:var(--text)}",
        ".label{fill:var(--text)}.value,.tick{fill:var(--muted)}",
        "</style>",
        f'<rect width="{width}" height="{height}" fill="var(--surface)"/>',
        '<text class="title" x="16" y="24">Intermediate tensors and arena size (MiB)</text>',
    ]
    legend_x = 16
    for key, name, _ in series:
        out.append(
            f'<rect x="{legend_x}" y="38" width="10" height="10" rx="2" fill="var(--{key})"/>'
        )
        out.append(f'<text class="label" x="{legend_x + 16}" y="47">{name}</text>')
        legend_x += 16 + int(6.5 * len(name)) + 28
    axis_bottom = height - 24
    tick = 0.0
    while tick <= limit:
        tx = x(tick)
        out.append(
            f'<line x1="{tx:.1f}" y1="{top - 8}" x2="{tx:.1f}" y2="{axis_bottom}" '
            'stroke="var(--grid)" stroke-width="1"/>'
        )
        out.append(
            f'<text class="tick" x="{tx:.1f}" y="{axis_bottom + 16}" text-anchor="middle">'
            f"{tick:g}</text>"
        )
        tick += step
    y = top
    for name, m in models.items():
        out.append(
            f'<text class="label" x="{left - 12}" y="{y + group / 2 + 4:.1f}" '
            f'text-anchor="end">{name}</text>'
        )
        for key, _, fn in series:
            mib = fn(m) / 2**20
            x0, x1 = left, max(x(mib), left + 4)
            r = min(4, (x1 - x0) / 2)
            # Square at the baseline, 4px rounded corners at the data end.
            d = (
                f"M{x0},{y} H{x1 - r:.1f} Q{x1:.1f},{y} {x1:.1f},{y + r} V{y + bar - r} "
                f"Q{x1:.1f},{y + bar} {x1 - r:.1f},{y + bar} H{x0} Z"
            )
            out.append(f'<path d="{d}" fill="var(--{key})"/>')
            out.append(f'<text class="value" x="{x1 + 6:.1f}" y="{y + bar - 3}">{mib:.1f}</text>')
            y += bar + gap
        y += group_gap - gap
    out.append("</svg>")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    parser.add_argument("--models", type=Path, default=ROOT / "data" / "models")
    parser.add_argument("--out", type=Path, default=ROOT / "results" / "graph")
    parser.add_argument(
        "--note",
        default="Times are provisional: the machine was running other work; counts and sizes "
        "do not depend on it.",
    )
    parser.add_argument("names", nargs="*", default=list(NAMES))
    args = parser.parse_args(argv)
    results: dict[str, Any] = {
        "date": date.today().isoformat(),
        "machine": f"{platform.machine()} {platform.platform(terse=True)}",
        "note": args.note,
        "models": {},
    }
    for name in args.names:
        path = args.models / f"{name}.onnx"
        if not path.exists():
            print(f"{name}: {path} not found (run scripts/export_models.py)", file=sys.stderr)
            return 1
        results["models"][name] = model_stats(path)
        m = results["models"][name]
        print(f"{name}: {m['onnx_nodes']} ONNX nodes, {m['kernels']} kernels", flush=True)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "models.json").write_text(json.dumps(results, indent=2) + "\n")
    (args.out / "models.md").write_text(markdown(results))
    (args.out / "memory.svg").write_text(memory_chart(results))
    return 0


if __name__ == "__main__":
    sys.exit(main())
